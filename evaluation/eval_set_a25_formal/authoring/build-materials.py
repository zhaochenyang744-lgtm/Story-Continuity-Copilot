import json
from pathlib import Path
BASE=Path(__file__).resolve().parents[2]

def save(p,d):
    p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def facts(root,w,rows):
    result=[]
    for subject,predicate,value,chapter,kind in rows:
        result.append(dict(memory_type=kind,subject=subject,predicate=predicate,value=value,chapter=chapter))
    save(root/'materials'/f'{w}-facts.json',result)

def threads(root,w,rows):
    result=[]
    for title,description,status,planted,resolved in rows:
        d=dict(title=title,description=description,status=status,planted_chapter=planted)
        if resolved:d['resolved_chapter']=resolved
        result.append(d)
    save(root/'materials'/f'{w}-foreshadows.json',result)

