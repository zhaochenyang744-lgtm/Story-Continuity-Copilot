"""Check scope, protected bytes, encoding and freeze without source-text output."""
from pathlib import Path
import hashlib
import json
import subprocess
import sys

REPO=Path(__file__).resolve().parents[3]
NAMES=('eval_set_a26_formal','eval_set_a2s6_formal')
ROOTS=[REPO/'evaluation'/n for n in NAMES]

def git(*args):
    return subprocess.check_output(['git',*args],cwd=REPO)

def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def allowed(p):
    return p=='.gitattributes' or any(p.startswith('evaluation/'+n+'/') for n in NAMES)

def main():
    base=json.loads((ROOTS[0]/'authoring/protected-baseline.json').read_text(encoding='utf-8'))
    branch=git('branch','--show-current').decode().strip()
    assert branch==base['branch']
    paths=git('diff','--name-only',base['head'],'--').decode('utf-8').splitlines()
    untracked=git('ls-files','--others','--exclude-standard','-z').decode('utf-8').split('\0')
    outside=[p for p in paths+untracked if p and not allowed(p)]
    protected=[p for p,h in base['sha256'].items() if p!='.gitattributes' and sha(REPO/p)!=h]
    original=git('show',base['head']+':.gitattributes')
    added=''.join('evaluation/'+n+'/** -text whitespace=-blank-at-eol,-blank-at-eof,-cr-at-eol\n' for n in NAMES).encode('utf-8')
    assert (REPO/'.gitattributes').read_bytes()==original+added
    encoding=[]
    files=[]
    for root in ROOTS:
        for p in root.rglob('*'):
            if not p.is_file(): continue
            rel=p.relative_to(REPO).as_posix()
            b=p.read_bytes()
            files.append(rel)
            try: b.decode('utf-8')
            except UnicodeError: encoding.append(rel+':utf8')
            if b.startswith(b'\xef\xbb\xbf'): encoding.append(rel+':bom')
            if b'\r' in b: encoding.append(rel+':cr')
    manifests=[]
    for root in ROOTS:
        errors=0
        lines=(root/'set.sha256').read_text(encoding='utf-8').splitlines()
        for line in lines:
            h,rel=line.split('  ',1)
            if sha(root/rel)!=h: errors+=1
        manifests.append({'set':root.name,'data_files':len(lines),'hash_errors':errors})
    assert not outside and not protected and not encoding
    assert all(m['hash_errors']==0 for m in manifests)
    if '--committed' in sys.argv:
        assert not git('status','--porcelain'), 'dirty_after_commit'
        for line in git('log','-2','--format=%B').decode('utf-8').splitlines():
            assert 'co-authored-by' not in line.lower() and 'generated by' not in line.lower()
    out={'status':'PASS','branch':branch,'outside_scope':len(outside),'protected_files':len(base['sha256'])-1,
         'protected_changes':len(protected),'encoding_errors':len(encoding),'new_files':len(files),
         'attributes_added':2,'manifests':manifests,'committed_check':'--committed' in sys.argv}
    if '--committed' not in sys.argv:
        (ROOTS[0]/'authoring/final-audit.json').write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps(out,ensure_ascii=False))

if __name__=='__main__':
    main()
